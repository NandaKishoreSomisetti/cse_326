// Translated text for an artwork (falls back to the original if edited by admin or not translated)
function artText(a) { return (!a.edited && ART_TEXT[lang] && ART_TEXT[lang][a.id]) || null; }
function artTitle(a) { const x = artText(a); return x ? x[0] : a.title; }
function artDesc(a) { const x = artText(a); return x ? x[1] : a.description; }
function artBio(a) {
  const b = BIO_TEXT[lang] && BIO_TEXT[lang][a.artist.name];
  if (b && !a.edited) return b;
  if (!a.artist.bio || a.artist.bio === "New artist on ArtMart.") return t("newArtist");
  return a.artist.bio;
}
